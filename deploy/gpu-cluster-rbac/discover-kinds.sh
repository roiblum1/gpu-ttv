#!/usr/bin/env bash
# Read-only: list the CRD kinds of one target cluster that may own GPU pods, as discoveredKinds
# values for this chart. It only runs `oc api-resources` (a GET of the discovery API).
#
#   KUBECONFIG=<target cluster> deploy/gpu-cluster-rbac/discover-kinds.sh [api-group ...] > discovered-<cluster>.yaml
#
# Default groups: Run:ai, KServe, LeaderWorkerSet, Kubeflow training, Knative serving. Kinds whose
# name suggests credentials are left out and listed in a comment. OC=<path> selects another oc/kubectl.
set -euo pipefail
cli=${OC:-oc}
if [ $# -gt 0 ]; then groups=("$@"); else
  groups=(run.ai serving.kserve.io leaderworkerset.x-k8s.io kubeflow.org serving.knative.dev)
fi

echo "# Generated by discover-kinds.sh ($cli api-resources) on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
echo "# Review it, then: helm template|install ... -f <this file> (README.md)."
echo "discoveredKinds:"
found=0
for group in "${groups[@]}"; do
  if ! listing=$("$cli" api-resources --api-group="$group" --verbs=get,list -o name); then
    echo "discover-kinds: '$cli api-resources --api-group=$group' failed" >&2
    exit 1
  fi
  kept=() skipped=()
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    plural=${name%%".$group"}
    case "$plural" in
      *secret*|*token*|*credential*|*password*) skipped+=("$plural") ;;
      *) kept+=("$plural") ;;
    esac
  done < <(printf '%s\n' "$listing" | sort -u)
  if [ ${#kept[@]} -eq 0 ]; then
    echo "  # $group: no readable kinds on this cluster"
  else
    found=1
    printf '  - apiGroup: %s\n    resources: [%s]\n' "$group" "$(IFS=,; echo "${kept[*]}" | sed 's/,/, /g')"
  fi
  if [ ${#skipped[@]} -gt 0 ]; then
    echo "    # left out (credentials): ${skipped[*]}"
  fi
done
[ "$found" = 1 ] || echo "  []"
